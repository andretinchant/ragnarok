def translate_select_content(content):
    """Translate the content inside select() calls."""
    # Handle select("opt1:opt2:opt3") format
    # and select("opt1", "opt2", "opt3") format
    options = content.split(':')
    translated = []
    for opt in options:
        translated.append(translate_text(opt))
    return ':'.join(translated)


def process_file(filepath):
    """Process a single NPC script file."""
    with open(filepath, 'r', encoding='utf-8', errors='replace') as f:
        lines = f.readlines()

    modified = False
    new_lines = []

    for line in lines:
        original_line = line

        # Skip comments
        stripped = line.lstrip()
        if stripped.startswith('//'):
            new_lines.append(line)
            continue

        # Process mes "..." lines
        # Match: mes "text"; or mes "text";  with optional whitespace
        mes_match = re.match(r'^(\s*mes\s+")(.*)(";?\s*)$', line)
        if mes_match:
            prefix = mes_match.group(1)
            text = mes_match.group(2)
            suffix = mes_match.group(3)

            # Don't translate NPC name lines like [Name]
            stripped_text = text.strip()

            # Translate the text
            translated = translate_text(text)

            if translated != text:
                line = prefix + translated + suffix
                modified = True
            new_lines.append(line)
            continue

        # Process select() calls - can span multiple patterns
        # Pattern 1: select("opt1:opt2:opt3")
        select_match = re.search(r'(select\()"([^"]*)"(\))', line)
        if select_match:
            before = line[:select_match.start()]
            prefix = select_match.group(1)
            content = select_match.group(2)
            suffix = select_match.group(3)
            after = line[select_match.end():]

            translated_content = translate_select_content(content)
            if translated_content != content:
                line = before + prefix + '"' + translated_content + '"' + suffix + after
                modified = True
            new_lines.append(line)
            continue

        # Pattern 2: select("opt1", "opt2", "opt3")
        select_match2 = re.search(r'select\(\s*"', line)
        if select_match2:
            # Find all quoted strings within this select call
            def translate_select_option(m):
                text = m.group(1)
                translated = translate_text(text)
                return '"' + translated + '"'

            # Find the select(...) portion
            sel_start = select_match2.start()
            # Find matching closing paren
            depth = 0
            sel_end = sel_start
            for i in range(sel_start, len(line)):
                if line[i] == '(':
                    depth += 1
                elif line[i] == ')':
                    depth -= 1
                    if depth == 0:
                        sel_end = i + 1
                        break

            select_portion = line[sel_start:sel_end]
            translated_select = re.sub(r'"([^"]*)"', translate_select_option, select_portion)

            if translated_select != select_portion:
                line = line[:sel_start] + translated_select + line[sel_end:]
                modified = True
            new_lines.append(line)
            continue

        # Also handle callsub lines that have quoted text (quest descriptions)
        callsub_match = re.search(r'(callsub\s+\w+,\d+,")(.*)(";?)', line)
        if callsub_match:
            prefix = line[:callsub_match.start(2)]
            text = callsub_match.group(2)
            suffix = line[callsub_match.end(2):]

            translated = translate_text(text)
            if translated != text:
                line = prefix + translated + suffix
                modified = True
            new_lines.append(line)
            continue

        new_lines.append(line)

    if modified:
        with open(filepath, 'w', encoding='utf-8', newline='\n') as f:
            f.writelines(new_lines)
        return True
    return False


