def translate_text(text):
    """Translate English text to Brazilian Portuguese without accented chars."""
    if not text or not text.strip():
        return text

    # Skip if already translated
    if any(pt_word in text for pt_word in ["voce", "Voce", "Cancelar", "missao", "Missao", "nao e", "Nao e"]):
        return text

    # Skip NPC name lines like "[Name]" - these are just NPC identifiers
    stripped = text.strip()
    if stripped.startswith("[") and stripped.endswith("]"):
        return text

    # Skip lines that are purely color codes, formatting, or very short symbols
    if stripped in ["...", "..", ".", "+", "-", "~", "!", "?", "*"]:
        return text

    # Skip lines with just special characters or numbers
    if re.match(r'^[\d\s\.\-\+\*\~\!\?\#\=]+$', stripped):
        return text

    # Apply direct phrase mappings
    for eng, ptbr in PHRASE_MAP.items():
        if text == eng:
            return ptbr

    # Full line translations using the comprehensive translator
    result = translate_line(text)
    return result


